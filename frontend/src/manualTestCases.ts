import type { ClaimSubmission } from './types'

export type ManualTestCategory =
  | 'Happy path'
  | 'Boundary / sub-limit'
  | 'Exclusion / wrong claim'
  | 'Escalation / risk'
  | 'Prompt injection'

export interface ManualTestCase {
  id: string
  title: string
  category: ManualTestCategory
  intent: string
  expected: string
  fields: ClaimSubmission
}

type PolicyId =
  | 'POL-HOME-01'
  | 'POL-HEALTH-01'
  | 'POL-MOTOR-01'
  | 'POL-TRAVEL-01'

function testCase(
  id: string,
  policyId: PolicyId,
  title: string,
  category: ManualTestCategory,
  intent: string,
  expected: string,
  policyStartDate: string,
  filedDate: string,
  claimantName: string,
  claimantCity: string,
  narrativeText: string,
  claimantGender: ClaimSubmission['claimant_gender'] = 'female',
): ManualTestCase {
  return {
    id,
    title,
    category,
    intent,
    expected,
    fields: {
      claim_id: '',
      policy_id: policyId,
      policy_start_date: policyStartDate,
      filed_date: filedDate,
      claimant_name: claimantName,
      claimant_gender: claimantGender,
      claimant_city: claimantCity,
      narrative_text: narrativeText,
    },
  }
}

